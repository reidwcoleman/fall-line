// Ride a run on autopilot to the results, then check the front page: node tools/loop.mjs [park]
import { chromium } from 'playwright-core';
import { CHROME, ANGLE } from './chrome.mjs';
const park = process.argv[2] ?? 'bigair';
const b = await chromium.launch({ executablePath: CHROME, headless: true, args: [ANGLE, '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('[error]', m.text().slice(0, 300)); });
await p.goto(`http://127.0.0.1:${process.env.PORT ?? 5270}/?park=${park}&menu=0&mode=run&auto=1&gear=${process.env.GEAR ?? 'board'}`, { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.__ready === true, null, { timeout: 180000 });
await p.waitForFunction(() => !document.getElementById('results').classList.contains('hidden'), null, { timeout: 400000, polling: 1000 });
await p.waitForTimeout(800);
await p.screenshot({ path: 'shots/loop_results.jpg', quality: 80 });
console.log('results', await p.evaluate(() => document.getElementById('rescard').innerText.replace(/\n+/g, ' | ')));
await p.click('#r-menu');
await p.waitForTimeout(1500);
await p.evaluate(() => window.__game.menu.setTab('board'));
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/loop_board.jpg', quality: 80 });
await p.evaluate(() => window.__game.menu.setTab('replays'));
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/loop_reps.jpg', quality: 80 });
console.log('reps', await p.evaluate(() => document.getElementById('reps').innerText.replace(/\n+/g, ' | ')));
await p.click('#reps [data-w]');
await p.waitForTimeout(3000);
console.log('watching', await p.evaluate(() => ({ on: window.__game.replay.on, menu: !document.getElementById('menu').classList.contains('hidden'), t: document.getElementById('rp-time').textContent })));
await p.screenshot({ path: 'shots/loop_watch.jpg', quality: 80 });
await p.keyboard.press('Escape');
await p.waitForTimeout(800);
console.log('after', await p.evaluate(() => ({ on: window.__game.replay.on, menu: !document.getElementById('menu').classList.contains('hidden'), tab: window.__game.menu.tab, flakes: window.__game.meta.flakes, xp: window.__game.meta.xp })));
await b.close();
